"""Evaluate the detectors on synthetic, labelled logs and write docs/EVALUATION.md.

    python scripts/evaluate.py                  # seeds 100-109, rewrite the report
    python scripts/evaluate.py --check          # fail if the committed report is stale
    python scripts/evaluate.py --seeds 1-5 --out -   # print to stdout

The output is deterministic: the same seeds give the same file on any machine.
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

from argus import __version__
from argus.evaluation import EvalReport, evaluate
from argus.events import SSH
from argus.ml.detector import AnomalyConfig
from argus.pipeline import ScanOptions, scan
from argus.rules.loader import builtin_rules
from argus.simulate import ACCESS_LOG, AUTH_LOG, simulate, write_simulation

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = ROOT / "docs" / "EVALUATION.md"


def parse_seeds(text: str) -> list[int]:
    seeds: list[int] = []
    for part in text.split(","):
        low, _, high = part.partition("-")
        seeds.extend(range(int(low), int(high or low) + 1))
    return seeds


def run(seeds: list[int], visitors: int) -> tuple[EvalReport, EvalReport]:
    """Default scan per seed, plus the opt-in SSH anomaly model as an experiment."""
    report = EvalReport()
    ssh_experiment = EvalReport()
    with tempfile.TemporaryDirectory(prefix="argus-eval-") as folder:
        for seed in seeds:
            simulation = simulate(seed, visitors_per_day=visitors)
            files = write_simulation(simulation, Path(folder) / str(seed))
            inputs = [files[ACCESS_LOG], files[AUTH_LOG]]
            report.merge(evaluate(scan(inputs, ScanOptions()), simulation.labels))
            ssh_only = ScanOptions(builtin=False, anomaly=AnomalyConfig(sources=(SSH,)))
            ssh_experiment.merge(evaluate(scan(inputs, ssh_only), simulation.labels))
    return report, ssh_experiment


def model_rows(report: EvalReport) -> list[str]:
    rows = [
        "| Source | Actors scored | Malicious | ROC-AUC | Flagged | Precision | Recall |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for source in sorted(report.models):
        model = report.models[source]
        auc = model.auc
        rows.append(
            f"| {source} | {model.actors:,} | {model.malicious:,} | "
            f"{'n/a' if auc is None else f'{auc:.3f}'} | {model.flagged} | "
            f"{pct(model.precision)} | {pct(model.recall)} |"
        )
    return rows


def pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.1%}"


def render(report: EvalReport, ssh_experiment: EvalReport, seeds: list[int], visitors: int) -> str:
    seed_text = (
        f"{seeds[0]}-{seeds[-1]}"
        if seeds == list(range(seeds[0], seeds[-1] + 1))
        else (",".join(map(str, seeds)))
    )
    threshold = AnomalyConfig().threshold
    lines = [
        "# Evaluation on synthetic data",
        "",
        "> Every number on this page comes from **synthetic** logs generated by the Argus",
        "> simulator. The traffic is shaped like real attacks as they appear in nginx and",
        "> OpenSSH logs, but it is not real traffic: these figures show that the detectors",
        "> behave as designed, not how they would score on a production network.",
        "",
        f"Generated by `python scripts/evaluate.py --seeds {seed_text}` with Argus {__version__}.",
        "The simulator and the anomaly model are seeded, so re-running the command reproduces",
        "this file exactly; CI runs it with `--check`.",
        "",
        "## Data",
        "",
        f"{len(seeds)} simulated runs (seeds {seed_text}), each 48 hours of an online shop with",
        f"{visitors} visitors a day, crawlers, an uptime monitor, an office NAT, SSH admins,",
        "CI and backup logins, background internet noise and 23 attack scenarios (1-2 runs",
        "each). Some scenario variants are built to slip under the rules (low-and-slow pacing,",
        "evasive SQL injection); they still count as expected detections.",
        "Thresholds were set before looking at these seeds.",
        "",
        "| Seed | Access lines | Auth lines | Events | Malformed injected | Malformed counted "
        "| Benign actors | Malicious actors | Alerts | Incidents |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    lines.extend(
        f"| {s.seed} | {s.access_lines:,} | {s.auth_lines:,} | {s.events:,} | "
        f"{s.malformed_injected} | {s.malformed_counted} | {s.benign_actors:,} | "
        f"{s.malicious_actors:,} | {s.alerts} | {s.incidents} |"
        for s in report.seeds
    )
    lines += [
        "",
        "## How it is scored",
        "",
        "An actor is a client address. Each malicious actor's label lists the rules that",
        "should fire for it.",
        "",
        "- **Precision** of a rule: alerted actors that are malicious / all alerted actors.",
        "- **Recall** of a rule: expected actors the rule alerted / actors expecting the rule.",
        "",
        "## Detections",
        "",
        "| Rule | Expected actors | Alerted actors | On benign actors | Precision | Recall |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    order = [rule.id for rule in builtin_rules()]
    for rule_id in order:
        m = report.detections[rule_id]
        lines.append(
            f"| `{rule_id}` | {m.expected} | {m.alerted} | {m.benign_alerted} | "
            f"{pct(m.precision)} | {pct(m.recall)} |"
        )
    total = report.total()
    lines.append(
        f"| **All rules (micro-average)** | {total.expected} | {total.alerted} | "
        f"{total.benign_alerted} | {pct(total.precision)} | {pct(total.recall)} |"
    )
    lines += ["", "### Where the misses come from", ""]
    if report.misses:
        lines += ["| Scenario | Rule | Missed actors |", "|---|---|---:|"]
        for (scenario, rule_id), count in sorted(
            report.misses.items(), key=lambda item: (-item[1], item[0])
        ):
            lines.append(f"| {scenario} | `{rule_id}` | {count} |")
    else:
        lines.append("No expected detection was missed.")
    lines += ["", "### Alerts on benign actors", ""]
    if report.false_alarms:
        lines += ["| Benign scenario | Rule | Actors |", "|---|---|---:|"]
        for (scenario, rule_id), count in sorted(
            report.false_alarms.items(), key=lambda item: (-item[1], item[0])
        ):
            lines.append(f"| {scenario} | `{rule_id}` | {count} |")
    else:
        lines.append("No rule fired on a benign actor.")
    lines += [
        "",
        "## Anomaly model (Isolation Forest)",
        "",
        "Default configuration: web actors only, 200 trees, sample size 256, flag threshold",
        f"{threshold}; actors with fewer than 5 events are not scored. Malicious here means any",
        "malicious label, including scenarios the rules already catch.",
        "",
        *model_rows(report),
        "",
        "### Experiment: SSH anomaly model (off by default)",
        "",
        'The same model fitted on SSH actors (`AnomalyConfig(sources=("ssh",))`). On an',
        "internet-facing SSH port most addresses are attackers, so the core assumption of",
        "Isolation Forest (anomalies are few) does not hold: the model isolates the handful",
        "of legitimate administrators instead. That is why Argus models web actors only",
        "unless asked otherwise; SSH coverage comes from the rules.",
        "",
        *model_rows(ssh_experiment),
    ]
    lines += [
        "",
        "## Reading the numbers",
        "",
        "- Precision near 100% is expected on synthetic data: benign traffic only contains",
        "  the awkward cases that were deliberately simulated (a travelling admin, an admin",
        "  logging in as root, crawlers, monitors). Real networks have more of them.",
        "- The misses table is the useful part: it shows which attack styles fixed",
        "  thresholds cannot see (low-and-slow guessing and scanning, payloads outside",
        "  the patterns).",
        "- The anomaly model ranks actors without labels. It complements the rules for",
        "  bursty, unusual behaviour and also flags unusual benign actors such as monitors",
        "  and crawlers, which is why its findings are scored lower than rule alerts.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--seeds", default="100-109", help="e.g. 100-109 or 1,2,5")
    parser.add_argument("--visitors", type=int, default=300, help="visitors per simulated day")
    parser.add_argument("--out", default=str(DEFAULT_OUT), help="output file, or - for stdout")
    parser.add_argument("--check", action="store_true", help="fail if --out is not up to date")
    args = parser.parse_args(argv)
    seeds = parse_seeds(args.seeds)
    report, ssh_experiment = run(seeds, args.visitors)
    text = render(report, ssh_experiment, seeds, args.visitors)
    if args.out == "-":
        sys.stdout.write(text)
        return 0
    out = Path(args.out)
    if args.check:
        current = out.read_text(encoding="utf-8") if out.exists() else ""
        if current != text:
            print(f"{out} is out of date; run python scripts/evaluate.py", file=sys.stderr)
            return 1
        print(f"{out} is up to date")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
