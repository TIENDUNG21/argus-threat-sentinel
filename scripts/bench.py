"""Time each stage of a scan on simulated logs and write docs/BENCHMARKS.md.

    python scripts/bench.py                       # default sizes, rewrite the doc
    python scripts/bench.py --visitors 300 --out -

Each size is a 48-hour simulation (seed 7) written to a temporary folder; every
stage runs ``--repeat`` times and the median wall time is reported. Unlike the
evaluation, these numbers depend on the machine, so the doc names it.
"""

from __future__ import annotations

import argparse
import os
import platform
import statistics
import sys
import tempfile
import time
from collections.abc import Callable
from pathlib import Path
from typing import TypeVar

import numpy as np

from argus import __version__
from argus.correlate import correlate
from argus.ml.detector import detect_anomalies
from argus.pipeline import ScanOptions, load_rule_set, read_inputs, scan
from argus.report.html import render_html
from argus.rules.engine import Engine
from argus.simulate import ACCESS_LOG, AUTH_LOG, simulate, write_simulation

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = ROOT / "docs" / "BENCHMARKS.md"
MACHINE = "Intel i7-14700K, 32 GB RAM, Windows 11"
T = TypeVar("T")


def timed(fn: Callable[[], T], repeat: int) -> tuple[float, T]:
    times, result = [], None
    for _ in range(repeat):
        began = time.perf_counter()
        result = fn()
        times.append(time.perf_counter() - began)
    assert result is not None
    return statistics.median(times), result


def bench_size(visitors: int, repeat: int) -> dict[str, float]:
    simulation = simulate(7, visitors_per_day=visitors)
    with tempfile.TemporaryDirectory(prefix="argus-bench-") as folder:
        files = write_simulation(simulation, Path(folder))
        paths = [files[ACCESS_LOG], files[AUTH_LOG]]
        options = ScanOptions()
        rules = load_rule_set(options)
        read_s, (events, stats, _) = timed(lambda: read_inputs(paths, options), repeat)
        rules_s, alerts = timed(lambda: Engine(rules).run(events), repeat)
        ml_s, (anomalies, models) = timed(lambda: detect_anomalies(events, options.anomaly), repeat)
        corr_s, _ = timed(lambda: correlate(alerts, anomalies, gap=options.gap), repeat)
        result = scan(paths, options)
        html_s, _ = timed(lambda: render_html(result), repeat)
        total_s, _ = timed(lambda: scan(paths, options), repeat)
    return {
        "lines": stats.total_lines,
        "events": len(events),
        "actors": sum(m.actors for m in models),
        "read": read_s,
        "rules": rules_s,
        "ml": ml_s,
        "correlate": corr_s,
        "html": html_s,
        "total": total_s,
    }


def render(rows: list[dict[str, float]], repeat: int) -> str:
    lines = [
        "# Benchmarks",
        "",
        f"Generated by `python scripts/bench.py` with Argus {__version__} on {MACHINE},",
        f"Python {platform.python_version()}, NumPy {np.__version__}. Median of {repeat} runs.",
        "Each row is one 48-hour simulation (seed 7); only the visitor count changes, so",
        "attack traffic is a smaller share of the larger runs.",
        "",
        "Stage times are measured separately on the same input. *Scan* is the full",
        "`argus scan` pipeline without writing reports, single process, single thread.",
        "The machine was running other jobs at the same time, so treat the figures as",
        "indicative; the small run in particular varies between invocations.",
        "",
        "| Visitors/day | Lines | Web actors modelled | Read + parse | Rules | Anomaly model "
        "| Correlate | HTML | Scan | Lines/s |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    lines.extend(
        f"| {row['visitors']:,.0f} | {row['lines']:,.0f} | {row['actors']:,.0f} "
        f"| {row['read']:.2f} s | {row['rules']:.2f} s | {row['ml']:.2f} s "
        f"| {_ms(row['correlate'])} | {_ms(row['html'])} "
        f"| {row['total']:.2f} s | {row['lines'] / row['total']:,.0f} |"
        for row in rows
    )
    largest = rows[-1]
    stages = {"read + parse": "read", "the rule engine": "rules", "the anomaly model": "ml"}
    name, key = max(stages.items(), key=lambda item: largest[item[1]])
    lines += [
        "",
        f"On the largest run the slowest stage is {name}, {largest[key] / largest['total']:.0%}",
        "of the scan. Parsing and the rule engine are pure Python and cost a roughly constant",
        "amount per line; the anomaly model works on one feature row per actor and is",
        "vectorised with NumPy.",
        "",
    ]
    return "\n".join(lines)


def _ms(seconds: float) -> str:
    return "<1 ms" if seconds < 0.0005 else f"{seconds * 1000:.0f} ms"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--visitors", default="300,1500,6000", help="comma-separated sizes")
    parser.add_argument("--repeat", type=int, default=3)
    parser.add_argument("--out", default=str(DEFAULT_OUT), help="output file, or - for stdout")
    args = parser.parse_args(argv)
    for name in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
        os.environ.setdefault(name, "1")
    rows = []
    for visitors in (int(v) for v in args.visitors.split(",")):
        row = bench_size(visitors, args.repeat)
        row["visitors"] = visitors
        print(
            f"{visitors} visitors/day: {row['lines']:,.0f} lines, scan {row['total']:.2f} s",
            file=sys.stderr,
        )
        rows.append(row)
    text = render(rows, args.repeat)
    if args.out == "-":
        sys.stdout.write(text)
    else:
        Path(args.out).write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
